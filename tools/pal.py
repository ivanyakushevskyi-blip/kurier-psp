"""Shared indexed palette: named ramps (dark -> light). Index 0 = transparent."""
PAL = [(0, 0, 0)]
R = {}


def ramp(name, cols):
    s = len(PAL)
    PAL.extend(cols)
    R[name] = list(range(s, s + len(cols)))


